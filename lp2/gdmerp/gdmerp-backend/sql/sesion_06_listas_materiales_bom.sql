-- GdmERP - Sesión 6: Tablas para Lista de Materiales (BOM) y Detalles de Receta
-- Ejecutar con un usuario con privilegios DBA (ej. SYSTEM) sobre Oracle 19c / 23ai.

-- 1. Permiso para que GDM_PRODUCCION pueda referenciar la tabla de productos de GDM_INVENTARIO
GRANT REFERENCES ON GDM_INVENTARIO.PRODUCTOS TO GDM_PRODUCCION;

-- 2. Tabla Cabecera: LISTAS_MATERIALES
CREATE TABLE GDM_PRODUCCION.LISTAS_MATERIALES (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(50 CHAR) NOT NULL CONSTRAINT UQ_LISTAS_MAT_CODIGO UNIQUE,
    PRODUCTO_TERMINADO_ID NUMBER(19,0) NOT NULL,
    CANTIDAD_BASE NUMBER(12,4) DEFAULT 1.0000 NOT NULL,
    CONSTRAINT FK_LM_PRODUCTO FOREIGN KEY (PRODUCTO_TERMINADO_ID)
        REFERENCES GDM_INVENTARIO.PRODUCTOS (ID)
);

-- 3. Tabla Detalle: DETALLES_LISTA_MATERIALES
CREATE TABLE GDM_PRODUCCION.DETALLES_LISTA_MATERIALES (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    LISTA_MATERIALES_ID NUMBER(19,0) NOT NULL,
    INSUMO_ID NUMBER(19,0) NOT NULL,
    CANTIDAD_REQUERIDA NUMBER(12,4) NOT NULL,
    CONSTRAINT FK_DETALLE_LISTA FOREIGN KEY (LISTA_MATERIALES_ID)
        REFERENCES GDM_PRODUCCION.LISTAS_MATERIALES (ID) ON DELETE CASCADE,
    CONSTRAINT FK_DETALLE_INSUMO FOREIGN KEY (INSUMO_ID)
        REFERENCES GDM_INVENTARIO.PRODUCTOS (ID)
);

-- 4. Permisos de manipulación de datos (DML) para el usuario de conexión JDBC de la aplicación (GDMERP_APP)
GRANT SELECT, INSERT, UPDATE, DELETE ON GDM_PRODUCCION.LISTAS_MATERIALES TO GDMERP_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON GDM_PRODUCCION.DETALLES_LISTA_MATERIALES TO GDMERP_APP;
