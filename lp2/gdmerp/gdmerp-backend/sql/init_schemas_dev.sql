-- =============================================================================
-- Script de Inicialización de Esquemas y Permisos para Desarrollo (gdmerp-backend)
-- Ejecutar conectado como SYSDBA en la PDB (FREEPDB1)
-- =============================================================================

ALTER SESSION SET CONTAINER = FREEPDB1;

-- 1. Crear esquemas requeridos por las entidades JPA
BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_CATALOGO IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_COMPRAS IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_CRM IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_VENTAS IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_INVENTARIO IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE USER GDM_PRODUCCION IDENTIFIED BY "123456" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

-- 2. Privilegios de conexión para cada esquema
GRANT CREATE SESSION, RESOURCE TO GDM_CATALOGO;
GRANT CREATE SESSION, RESOURCE TO GDM_COMPRAS;
GRANT CREATE SESSION, RESOURCE TO GDM_CRM;
GRANT CREATE SESSION, RESOURCE TO GDM_VENTAS;
GRANT CREATE SESSION, RESOURCE TO GDM_INVENTARIO;
GRANT CREATE SESSION, RESOURCE TO GDM_PRODUCCION;

-- 3. Privilegios para el usuario de la aplicación (GDMERP_APP)
GRANT DBA TO GDMERP_APP;
GRANT CREATE ANY TABLE, ALTER ANY TABLE, DROP ANY TABLE, SELECT ANY TABLE, INSERT ANY TABLE, UPDATE ANY TABLE, DELETE ANY TABLE TO GDMERP_APP;
GRANT CREATE ANY SEQUENCE, ALTER ANY SEQUENCE, DROP ANY SEQUENCE, SELECT ANY SEQUENCE TO GDMERP_APP;
GRANT CREATE ANY INDEX, ALTER ANY INDEX, DROP ANY INDEX TO GDMERP_APP;

-- 4. Secuencia para tickets de venta
BEGIN
  EXECUTE IMMEDIATE 'CREATE SEQUENCE GDM_VENTAS.SEQ_TICKET_VENTA START WITH 1 INCREMENT BY 1 NOCACHE';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/
