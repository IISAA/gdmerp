-- 1. Creación de la Tabla GDM_INVENTARIO.UNIDADES_MEDIDA
CREATE TABLE GDM_INVENTARIO.UNIDADES_MEDIDA (
    ID NUMBER(19,0) GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(20 CHAR) NOT NULL,
    CODIGO_SUNAT VARCHAR2(10 CHAR),
    NOMBRE VARCHAR2(80 CHAR) NOT NULL,
    SIMBOLO VARCHAR2(15 CHAR) NOT NULL,
    CATEGORIA VARCHAR2(30 CHAR) NOT NULL,
    FACTOR_CONVERSION NUMBER(12,4) NOT NULL,
    PERMITE_DECIMALES NUMBER(1,0) DEFAULT 1 NOT NULL,
    ACTIVO NUMBER(1,0) DEFAULT 1 NOT NULL,
    CONSTRAINT UQ_UNIDAD_MEDIDA_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_UM_DECIMALES CHECK (PERMITE_DECIMALES IN (0, 1)),
    CONSTRAINT CK_UM_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT CK_UM_FACTOR CHECK (FACTOR_CONVERSION > 0),
    CONSTRAINT CK_UM_CATEGORIA CHECK (CATEGORIA IN ('MASA', 'LONGITUD', 'VOLUMEN', 'SUPERFICIE', 'UNIDAD_EMPAQUE'))
);

-- Comentarios explicativos en el diccionario de datos de Oracle
COMMENT ON TABLE GDM_INVENTARIO.UNIDADES_MEDIDA IS 'Catálogo internacional (SI y UN/ECE) de unidades de medida con factores de conversión respecto a la unidad base de su categoría.';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.CODIGO IS 'Código interno estandarizado único (ej. KG, GR, LT, UND).';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.CODIGO_SUNAT IS 'Código del estándar SUNAT / UN/ECE Rec 20 (ej. KGM, GRM, LTR, NIU).';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.NOMBRE IS 'Denominación descriptiva oficial de la unidad de medida.';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.SIMBOLO IS 'Símbolo gráfico o abreviatura normalizada (ej. kg, g, L, m, und).';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.CATEGORIA IS 'Clasificación física: MASA, LONGITUD, VOLUMEN, SUPERFICIE, UNIDAD_EMPAQUE.';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.FACTOR_CONVERSION IS 'Proporción aritmética con respecto a la unidad base (Base = 1.0000).';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.PERMITE_DECIMALES IS 'Indicador booleano (1=Sí, 0=No). Discretas usan 0, continuas usan 1.';
COMMENT ON COLUMN GDM_INVENTARIO.UNIDADES_MEDIDA.ACTIVO IS 'Estado operativo del registro (1=Activo, 0=Inactivo).';

-- 2. Permisos DML para el usuario de conexión JDBC de la aplicación
GRANT SELECT, INSERT, UPDATE, DELETE ON GDM_INVENTARIO.UNIDADES_MEDIDA TO GDMERP_APP;

-- 3. Data Seeder Idempotente en Oracle (MERGE) para Unidades Estándar
MERGE INTO GDM_INVENTARIO.UNIDADES_MEDIDA t
USING (
    SELECT 'KG' AS CODIGO, 'KGM' AS CODIGO_SUNAT, 'Kilogramo' AS NOMBRE, 'kg' AS SIMBOLO, 'MASA' AS CATEGORIA, 1.0000 AS FACTOR_CONVERSION, 1 AS PERMITE_DECIMALES, 1 AS ACTIVO FROM DUAL UNION ALL
    SELECT 'GR', 'GRM', 'Gramo', 'g', 'MASA', 0.0010, 1, 1 FROM DUAL UNION ALL
    SELECT 'MG', 'MGM', 'Miligramo', 'mg', 'MASA', 0.0001, 1, 1 FROM DUAL UNION ALL
    SELECT 'TON', 'TNE', 'Tonelada Métrica', 't', 'MASA', 1000.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'QQ', 'CWA', 'Quintal (46 kg)', 'qq', 'MASA', 46.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'M', 'MTR', 'Metro', 'm', 'LONGITUD', 1.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'CM', 'CMT', 'Centímetro', 'cm', 'LONGITUD', 0.0100, 1, 1 FROM DUAL UNION ALL
    SELECT 'MM', 'MMT', 'Milímetro', 'mm', 'LONGITUD', 0.0010, 1, 1 FROM DUAL UNION ALL
    SELECT 'ROL_LIN', 'RO', 'Bobina / Rollo Lineal', 'rol_m', 'LONGITUD', 1.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'LT', 'LTR', 'Litro', 'L', 'VOLUMEN', 1.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'ML', 'MLT', 'Mililitro', 'ml', 'VOLUMEN', 0.0010, 1, 1 FROM DUAL UNION ALL
    SELECT 'GAL', 'GLL', 'Galón (US)', 'gal', 'VOLUMEN', 3.7854, 1, 1 FROM DUAL UNION ALL
    SELECT 'M3', 'MTQ', 'Metro Cúbico', 'm³', 'VOLUMEN', 1000.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'M2', 'MTK', 'Metro Cuadrado', 'm²', 'SUPERFICIE', 1.0000, 1, 1 FROM DUAL UNION ALL
    SELECT 'UND', 'NIU', 'Unidad', 'und', 'UNIDAD_EMPAQUE', 1.0000, 0, 1 FROM DUAL UNION ALL
    SELECT 'CAJ', 'BX', 'Caja', 'caj', 'UNIDAD_EMPAQUE', 1.0000, 0, 1 FROM DUAL UNION ALL
    SELECT 'SAC', 'SA', 'Saco', 'sac', 'UNIDAD_EMPAQUE', 1.0000, 0, 1 FROM DUAL UNION ALL
    SELECT 'ROL', 'RO', 'Rollo de Empaque', 'rol', 'UNIDAD_EMPAQUE', 1.0000, 0, 1 FROM DUAL UNION ALL
    SELECT 'PAQ', 'PK', 'Paquete', 'paq', 'UNIDAD_EMPAQUE', 1.0000, 0, 1 FROM DUAL
) s ON (t.CODIGO = s.CODIGO)
WHEN MATCHED THEN
    UPDATE SET 
        t.CODIGO_SUNAT = s.CODIGO_SUNAT,
        t.NOMBRE = s.NOMBRE,
        t.SIMBOLO = s.SIMBOLO,
        t.CATEGORIA = s.CATEGORIA,
        t.FACTOR_CONVERSION = s.FACTOR_CONVERSION,
        t.PERMITE_DECIMALES = s.PERMITE_DECIMALES,
        t.ACTIVO = s.ACTIVO
WHEN NOT MATCHED THEN
    INSERT (CODIGO, CODIGO_SUNAT, NOMBRE, SIMBOLO, CATEGORIA, FACTOR_CONVERSION, PERMITE_DECIMALES, ACTIVO)
    VALUES (s.CODIGO, s.CODIGO_SUNAT, s.NOMBRE, s.SIMBOLO, s.CATEGORIA, s.FACTOR_CONVERSION, s.PERMITE_DECIMALES, s.ACTIVO);

COMMIT;
